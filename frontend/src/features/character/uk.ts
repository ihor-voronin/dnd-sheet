const norm = (value: string): string =>
  value.trim().toLowerCase().replace(/\s+/g, " ").replace(/[’ʼ]/g, "'");

export function ukFeature(nameEn: string): UkText | undefined {
  return FEATURES[norm(nameEn)];
}

export function ukSpell(nameEn: string): UkText | undefined {
  return SPELLS[norm(nameEn)];
}

export function ukTerm(nameEn: string): string | undefined {
  return TERMS[norm(nameEn)];
}

/** Назва виду чи підраси українською (англійська — у дужках на екрані). */
export function speciesLabel(nameEn: string): string {
  const uk = SPECIES_UK[norm(nameEn)] ?? TERMS[norm(nameEn)];
  if (!uk || norm(uk) === norm(nameEn)) return nameEn;
  // «Драконороджений (хроматичний) (Dragonborn (Chromatic))» — забагато
  // дужок; для таких назв англійська йде через тире.
  return nameEn.includes("(") ? `${uk} — ${nameEn}` : `${uk} (${nameEn})`;
}

/** Назва предмета: звірене з SRD, далі великий словник, далі ручний. */
export function ukItem(nameEn: string): string | undefined {
  return ITEM_SRD[norm(nameEn)] ?? ITEM_NAMES[norm(nameEn)] ?? ITEMS[norm(nameEn)];
}

/** Ключ, за яким шукаємо переклад у словниках і в `items-uk.json`. */
export function itemKey(nameEn: string): string {
  return norm(nameEn);
}

export function ukBackground(key: string): UkBackground | undefined {
  return BACKGROUNDS[norm(key)];
}

/** «Диявол» для ключа «phb-2014/subclass/the-fiend»; без перекладу — людська назва. */
export function ukSubclass(key: string): string | undefined {
  const tail = norm(key.split("/").pop() ?? key);
  return TERMS[tail];
}

/** Назва українською з оригіналом у дужках: «Довгий меч (Longsword)». */
export function withEnglish(nameEn: string, uk?: string | null): string {
  if (!uk || norm(uk) === norm(nameEn)) return nameEn;
  return `${uk} (${nameEn})`;
}

export function featureLabel(nameEn: string): string {
  return withEnglish(nameEn, ukFeature(nameEn)?.name);
}

export function spellLabel(nameEn: string): string {
  return withEnglish(nameEn, ukSpell(nameEn)?.name);
}

export function itemLabel(nameEn: string): string {
  return withEnglish(nameEn, ukItem(nameEn));
}

export function termLabel(nameEn: string): string {
  return withEnglish(nameEn, ukTerm(nameEn));
}

